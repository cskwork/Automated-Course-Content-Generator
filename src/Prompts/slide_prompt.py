"""
슬라이드 최적화 프롬프트
교육 콘텐츠를 슬라이드 형태에 최적화된 형태로 변환합니다.
"""

SLIDE_OPTIMIZATION_PROMPT = """
당신은 교육 콘텐츠를 슬라이드 프레젠테이션에 최적화된 형태로 변환하는 전문가입니다.

주어진 교육 콘텐츠를 다음 원칙에 따라 슬라이드용으로 최적화해주세요:

## 슬라이드 최적화 원칙:

1. **간결성 (Conciseness)**
   - 한 슬라이드당 핵심 포인트 1-3개만 포함
   - 문장을 짧고 명확하게 작성
   - 불필요한 설명 제거

2. **시각적 구조화 (Visual Structure)**
   - 제목과 부제목을 명확히 구분
   - 번호 매기기나 불릿 포인트 활용
   - 중요한 내용은 강조 표시

3. **학습자 친화적 (Learner-Friendly)**
   - 이해하기 쉬운 언어 사용
   - 예시와 설명을 균형있게 배치
   - 단계별 학습 진행

4. **상호작용 요소 (Interactive Elements)**
   - 질문이나 생각해볼 거리 포함
   - 이미지나 도표가 필요한 부분에 [이미지: 설명] 표시
   - 활동이나 실습 제안

## 슬라이드 분할 기준:

- **개념 소개**: 새로운 개념당 1-2 슬라이드
- **설명**: 복잡한 내용은 여러 슬라이드로 분할
- **예시**: 예시마다 별도 슬라이드
- **정리**: 섹션 마무리용 요약 슬라이드

## 출력 형식:

각 슬라이드는 다음 형식으로 구분하여 작성:

---SLIDE---
제목: [슬라이드 제목]
내용:
[슬라이드 내용 - 간결하고 명확하게]
---END---

## 예시:

---SLIDE---
제목: 분수의 개념
내용:
# 분수란 무엇일까요?

- 전체를 여러 부분으로 나눈 것
- 분자: 선택한 부분의 개수
- 분모: 전체를 나눈 부분의 개수

[이미지: 피자를 8조각으로 나누고 3조각을 먹은 모습]

💡 **생각해보기**: 피자 8조각 중 3조각을 먹었다면?
---END---

이제 다음 교육 콘텐츠를 슬라이드용으로 최적화해주세요:

{content}
"""

def get_slide_optimization_prompt(content: str) -> str:
    """슬라이드 최적화 프롬프트를 생성합니다."""
    return SLIDE_OPTIMIZATION_PROMPT.format(content=content)